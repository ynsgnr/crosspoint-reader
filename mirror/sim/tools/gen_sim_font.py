#!/usr/bin/env python3
"""Bakes DejaVu Sans into sim/SimFontData.h (1-bit glyphs) for the host simulator. Needs Pillow + DejaVu fonts.
The output is committed; run this only to change the simulator fonts. Not used on the device."""
import sys
from PIL import Image, ImageDraw, ImageFont

FONTS = [("Body", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 20),
         ("Small", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 15),
         ("Title", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 26)]
CPS = list(range(32, 127)) + list(range(160, 256)) + [0x2026, 0x2014, 0x2019]

out = ["// GENERATED by sim/tools/gen_sim_font.py (DejaVu Sans, Bitstream Vera license). Host simulator only.",
       "// clang-format off",
       "#pragma once", "#include <cstddef>", "#include <cstdint>", "",
       "namespace mirror::sim {",
       "struct SimGlyph { uint32_t cp; uint8_t adv, w, h; int8_t bx, by; uint32_t off; };",
       "struct SimFont { int size, lineHeight; const SimGlyph* glyphs; size_t count; const uint8_t* bits; };", ""]
for name, path, size in FONTS:
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    bits, glyphs = bytearray(), []
    for cp in CPS:
        ch = chr(cp)
        adv = int(round(f.getlength(ch)))
        l, t, r, b = f.getbbox(ch, anchor="la")
        w, h = max(0, r - l), max(0, b - t)
        off = len(bits)
        if w and h:
            canvas = Image.new("L", (w + 2, h + 2), 0)
            ImageDraw.Draw(canvas).text((-l, -t), ch, font=f, fill=255, anchor="la")
            for y in range(h):
                row = 0
                nb = (w + 7) // 8
                rowbytes = bytearray(nb)
                for x in range(w):
                    if canvas.getpixel((x, y)) >= 128:
                        rowbytes[x // 8] |= 0x80 >> (x % 8)
                bits += rowbytes
        glyphs.append((cp, adv, w, h, l, t, off))
    out.append("inline constexpr SimGlyph k%sGlyphs[] = {" % name)
    for g in glyphs:
        out.append("  {0x%X, %d, %d, %d, %d, %d, %d}," % g)
    out.append("};")
    out.append("inline constexpr uint8_t k%sBits[] = {" % name)
    for i in range(0, len(bits), 24):
        out.append("  " + ",".join("0x%02X" % b for b in bits[i:i + 24]) + ",")
    if not bits:
        out.append("  0")
    out.append("};")
    out.append("inline constexpr SimFont k%sFont = {%d, %d, k%sGlyphs, sizeof(k%sGlyphs) / sizeof(SimGlyph), k%sBits};\n"
               % (name, size, asc + desc, name, name, name))
out.append("}  // namespace mirror::sim")
open(sys.argv[1] if len(sys.argv) > 1 else "SimFontData.h", "w").write("\n".join(out) + "\n")
